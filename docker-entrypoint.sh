#!/bin/sh
# =====================================================================
#  نقطة تشغيل الحاوية:
#   1) الانتظار حتى تجهز قاعدة البيانات
#   2) تطبيق مخطط قاعدة البيانات (idempotent — آمن في كل تشغيل)
#   3) إدخال الخدمات والمدير الافتراضي (لا يكرر البيانات)
#   4) تشغيل السيرفر
# =====================================================================
set -e

echo "▶ تشغيل نظام حجز صيانة السيارات..."

if [ -z "$DATABASE_URL" ]; then
  echo "✖ متغير DATABASE_URL غير موجود — تحقق من ملف .env.docker"
  exit 1
fi

echo "▶ انتظار قاعدة البيانات وتطبيق المخطط (migrations)..."
node scripts/migrate.js

if [ "${SEED_ON_START:-true}" = "true" ]; then
  echo "▶ تهيئة البيانات الأولية (خدمات + مدير النظام)..."
  node scripts/seed.js || echo "⚠️ تم تخطي خطوة البيانات الأولية — راجع الرسالة أعلاه."
fi

echo "✅ جاهز — تشغيل السيرفر على المنفذ ${PORT:-3000}"
exec "$@"
